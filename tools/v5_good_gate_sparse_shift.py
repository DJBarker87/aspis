#!/usr/bin/env python3
"""Derive the exact natural-basis multiply-by-X map used by the v5 Good gate.

The input conversion table is parsed from the verifier source, so this tool
cannot silently drift to a second copy of the constants.  Arithmetic is exact
in M31.  Before emitting Rust constants it checks every ordinary monomial
basis vector against the defining commuting square

    S * (Conv * e_d) = Conv * e_(d+1).

The GoodA/GoodB construction only shifts polynomials of degree at most 46;
therefore natural coordinate 47 is zero before every shift.  The tool reports
both the complete matrix and the reachable 0..46-column support.
"""

from __future__ import annotations

import argparse
import pathlib
import re


P = 2**31 - 1
WIDTH = 48
PARITY_WIDTH = WIDTH // 2


def parse_conversion(source: pathlib.Path) -> list[list[int]]:
    text = source.read_text(encoding="utf-8")
    match = re.search(
        r"const MONOMIAL_TO_NATURAL_PARITY:.*?= \[(.*?)\n\];\n\npub type",
        text,
        re.S,
    )
    if match is None:
        raise SystemExit("MONOMIAL_TO_NATURAL_PARITY was not found")
    words = [int(word) for word in re.findall(r"\b\d+\b", match.group(1))]
    if len(words) != PARITY_WIDTH * PARITY_WIDTH:
        raise SystemExit(f"expected 576 conversion entries, found {len(words)}")
    return [
        words[row * PARITY_WIDTH : (row + 1) * PARITY_WIDTH]
        for row in range(PARITY_WIDTH)
    ]


def conversion_matrix(table: list[list[int]]) -> list[list[int]]:
    # natural = conversion * ordinary
    conversion = [[0] * WIDTH for _ in range(WIDTH)]
    for degree in range(WIDTH):
        parity = degree & 1
        for index in range(degree // 2 + 1):
            conversion[parity + 2 * index][degree] = table[degree // 2][index] % P
    return conversion


def invert(matrix: list[list[int]]) -> list[list[int]]:
    augmented = [
        [entry % P for entry in matrix[row]]
        + [int(row == column) for column in range(WIDTH)]
        for row in range(WIDTH)
    ]
    for column in range(WIDTH):
        pivot = next(
            (row for row in range(column, WIDTH) if augmented[row][column]),
            None,
        )
        if pivot is None:
            raise SystemExit("conversion matrix is singular")
        augmented[column], augmented[pivot] = augmented[pivot], augmented[column]
        inverse = pow(augmented[column][column], P - 2, P)
        augmented[column] = [(entry * inverse) % P for entry in augmented[column]]
        for row in range(WIDTH):
            if row == column or augmented[row][column] == 0:
                continue
            scale = augmented[row][column]
            augmented[row] = [
                (left - scale * right) % P
                for left, right in zip(augmented[row], augmented[column], strict=True)
            ]
    return [row[WIDTH:] for row in augmented]


def multiply(left: list[list[int]], right: list[list[int]]) -> list[list[int]]:
    return [
        [
            sum(left[row][inner] * right[inner][column] for inner in range(WIDTH))
            % P
            for column in range(WIDTH)
        ]
        for row in range(WIDTH)
    ]


def matrix_vector(matrix: list[list[int]], vector: list[int]) -> list[int]:
    return [
        sum(matrix[row][column] * vector[column] for column in range(WIDTH)) % P
        for row in range(WIDTH)
    ]


def derive_shift(conversion: list[list[int]]) -> list[list[int]]:
    inverse = invert(conversion)
    ordinary_shift_times_inverse = [[0] * WIDTH for _ in range(WIDTH)]
    for degree in range(1, WIDTH):
        ordinary_shift_times_inverse[degree] = inverse[degree - 1][:]
    return multiply(conversion, ordinary_shift_times_inverse)


def check_commuting_square(
    conversion: list[list[int]], shift: list[list[int]]
) -> None:
    for degree in range(WIDTH):
        ordinary = [0] * WIDTH
        ordinary[degree] = 1
        natural = matrix_vector(conversion, ordinary)
        shifted = matrix_vector(shift, natural)
        expected_ordinary = [0] * WIDTH
        if degree + 1 < WIDTH:
            expected_ordinary[degree + 1] = 1
        expected = matrix_vector(conversion, expected_ordinary)
        if shifted != expected:
            raise SystemExit(f"commuting-square failure at ordinary degree {degree}")


def emit_rust(shift: list[list[int]]) -> None:
    print("// Generated by tools/v5_good_gate_sparse_shift.py; arithmetic is mod M31.")
    print("const NATURAL_MUL_X_SPARSE: [&[(usize, u32)]; 48] = [")
    for column in range(WIDTH):
        entries = [
            (row, shift[row][column])
            for row in range(WIDTH)
            if shift[row][column] != 0
        ]
        body = ", ".join(f"({row}, {value})" for row, value in entries)
        print(f"    &[{body}], // input {column}")
    print("];")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "source",
        nargs="?",
        type=pathlib.Path,
        default=pathlib.Path("programs/aspis-verifier/src/v5_good_gate_probe.rs"),
    )
    args = parser.parse_args()
    conversion = conversion_matrix(parse_conversion(args.source))
    shift = derive_shift(conversion)
    check_commuting_square(conversion, shift)
    complete = sum(entry != 0 for row in shift for entry in row)
    reachable = sum(
        shift[row][column] != 0
        for row in range(WIDTH)
        for column in range(WIDTH - 1)
    )
    print(f"// complete nonzeros: {complete}; reachable columns 0..46: {reachable}")
    emit_rust(shift)


if __name__ == "__main__":
    main()
