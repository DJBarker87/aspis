#!/usr/bin/env python3
"""Generate the kernel-checked cap-203 delta over the V6 cap-209 certificate.

The V6 certificate already proves the dependency cone for frontier values
210..288.  V7 admits only frontiers up to 203, so this generator emits exactly
the missing cone needed for the six additional rejected values 204..209.  The
generator is untrusted: Lean reconstructs every coefficient with `norm_num`;
`native_decide`, `sorry`, and `admit` are never used.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import generate_v6_compact_frontier_tail as v6


V6_CAP = 209
V7_CAP = 203
DEPTH = v6.DEPTH
SELECTED = v6.SELECTED
LOOSE_MAX = v6.LOOSE_MAX


def dependencies(depth: int, selected: int, frontier: int) -> set[tuple[int, int, int]]:
    if depth == 0:
        return set()
    previous_depth = depth - 1
    result: set[tuple[int, int, int]] = set()
    if frontier > 0 and frontier - 1 <= selected * previous_depth:
        result.add((previous_depth, selected, frontier - 1))
    for left_selected in range(1, selected):
        right_selected = selected - left_selected
        for left_frontier in range(frontier + 1):
            right_frontier = frontier - left_frontier
            if (
                left_frontier <= left_selected * previous_depth
                and right_frontier <= right_selected * previous_depth
            ):
                result.add((previous_depth, left_selected, left_frontier))
                result.add((previous_depth, right_selected, right_frontier))
    return result


def dependency_closure(first_frontier: int) -> set[tuple[int, int, int]]:
    needed = {
        (DEPTH, SELECTED, frontier)
        for frontier in range(first_frontier, LOOSE_MAX + 1)
    }
    pending = list(needed)
    while pending:
        state = pending.pop()
        for dependency in dependencies(*state):
            if dependency not in needed:
                needed.add(dependency)
                pending.append(dependency)
    return needed


def local_name(depth: int, selected: int, frontier: int) -> str:
    return f"certificate_{depth}_{selected}_{frontier}"


def v6_name(state: tuple[int, int, int]) -> str:
    return (
        "AspisV6CompactFrontierTailCertificate."
        + local_name(*state)
    )


def attribute_lines(action: str, names: list[str]) -> list[str]:
    width = 8
    return [
        f"attribute [{action}] " + " ".join(names[start : start + width])
        for start in range(0, len(names), width)
    ]


def generate(output: Path) -> None:
    tables = v6.coefficient_tables()
    base = dependency_closure(V6_CAP + 1)
    full = dependency_closure(V7_CAP + 1)
    missing = full - base
    assert len(missing) == 652

    final_row = tables[DEPTH][SELECTED]
    delta = sum(
        final_row.get(frontier, 0) * (1 << frontier)
        for frontier in range(V7_CAP + 1, V6_CAP + 1)
    )
    assert delta == int(
        "6915291501979218758486550434503151696943423928716542558271246420848672768"
    )

    lines = [
        "import AspisFormal.V6CompactFrontierTailCertificate",
        "",
        "/-! Generated by `tools/generate_v7_compact_frontier_delta.py`.",
        "Every declaration uses ordinary kernel-checked arithmetic. -/",
        "",
        "set_option autoImplicit false",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 0",
        "",
        "namespace AspisV7CompactFrontierDeltaCertificate",
        "",
        "open AspisV6CompactFrontierRecurrence",
        "",
    ]

    previous_local: list[str] = []
    previous_base: list[str] = []
    for depth in range(DEPTH + 1):
        states = sorted(state for state in missing if state[0] == depth)
        current_local: list[str] = []
        current_base = sorted(
            {
                v6_name(dependency)
                for state in states
                for dependency in dependencies(*state)
                if dependency in base
            }
        )

        if current_base:
            lines.extend(attribute_lines("simp", current_base))
            lines.append("")
        lines.append(f"/-! ## Depth {depth} missing recurrence coefficients -/")
        lines.append("")
        for _, selected, frontier in states:
            value = tables[depth].get(selected, {}).get(frontier, 0)
            name = local_name(depth, selected, frontier)
            current_local.append(name)
            lines.extend(
                [
                    f"theorem {name} :",
                    f"    frontierCoeff {depth} {selected} {frontier} = {value} := by",
                ]
            )
            if depth == 0:
                lines.append("  norm_num [frontierCoeff]")
            else:
                lines.extend(
                    [
                        "  rw [frontierCoeff]",
                        "  norm_num [Finset.sum_range_succ,",
                        "    frontierCoeff_eq_zero_of_frontier_gt_mul]",
                    ]
                )
            lines.append("")

        if previous_local:
            lines.extend(attribute_lines("-simp", previous_local))
        if previous_base:
            lines.extend(attribute_lines("-simp", previous_base))
        if current_local:
            lines.extend(attribute_lines("simp", current_local))
        lines.append("")
        previous_local = current_local
        previous_base = current_base

    lines.extend(
        [
            "/-- Exact schedules admitted by cap 209 but rejected by cap 203. -/",
            "def compactDelta : Nat :=",
            f"  ∑ frontier ∈ Finset.Icc {V7_CAP + 1} {V6_CAP},",
            f"    concreteFrontierCount {DEPTH} {SELECTED} frontier",
            "",
            "def expectedCompactDelta : Nat :=",
            f"  {delta}",
            "",
            "theorem compactDelta_eq_expected :",
            "    compactDelta = expectedCompactDelta := by",
            "  norm_num [compactDelta, concreteFrontierCount,",
            "    Finset.sum_Icc_succ_top]",
            "",
            "#print axioms compactDelta_eq_expected",
            "",
            "end AspisV7CompactFrontierDeltaCertificate",
            "",
        ]
    )
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generate(args.output)


if __name__ == "__main__":
    main()
