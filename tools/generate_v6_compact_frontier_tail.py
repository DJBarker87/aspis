#!/usr/bin/env python3
"""Generate the ordinary-kernel V6 frontier-tail certificate.

The certificate contains 4,999 recurrence cells. Keeping every cell in one
Lean environment used more than 40 GiB while serialising the final module, so
the generated source is deliberately a DAG:

* every depth is divided into bounded chunks;
* a chunk imports only the previous-depth aggregator;
* an aggregator imports its depth's chunks, removes the preceding depth from
  the simp set, and adds the current depth; and
* the historical public module is a small wrapper over the depth-18
  aggregator.

All public theorem names and statements are unchanged. The generator remains
untrusted: Lean reconstructs every coefficient with ``norm_num``;
``native_decide``, ``sorry``, and ``admit`` are never emitted.

Normal generation replaces the complete generated set deterministically and
removes obsolete files in its private generated directory. ``--check`` is
strict: it rejects missing, changed, or unexpected generated files.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path


DEPTH = 18
SELECTED = 16
CAP = 209
LOOSE_MAX = DEPTH * SELECTED
CHUNK_SIZE = 48
CHUNK_COST = 100
GENERATED_HEADER = (
    "/-! Generated by `tools/generate_v6_compact_frontier_tail.py`; "
    "do not edit."
)
MODULE_PREFIX = "AspisFormal.V6CompactFrontierTailCertificate"


def coefficient_tables() -> list[dict[int, dict[int, int]]]:
    current: dict[int, dict[int, int]] = {1: {0: 1}}
    result = [current]
    for _ in range(DEPTH):
        following: dict[int, dict[int, int]] = {}
        for selected in range(1, SELECTED + 1):
            row: defaultdict[int, int] = defaultdict(int)
            for frontier, count in current.get(selected, {}).items():
                row[frontier + 1] += count
            for left_selected in range(1, selected):
                for left_frontier, left_count in current.get(
                    left_selected, {}
                ).items():
                    for right_frontier, right_count in current.get(
                        selected - left_selected, {}
                    ).items():
                        row[left_frontier + right_frontier] += (
                            left_count * right_count
                        )
            following[selected] = dict(row)
        current = following
        result.append(current)
    return result


def dependencies(
    depth: int, selected: int, frontier: int
) -> set[tuple[int, int, int]]:
    """Exact previous-depth cells exposed by one unfolded recurrence."""
    if depth == 0:
        return set()
    previous_depth = depth - 1
    result: set[tuple[int, int, int]] = set()
    if frontier > 0 and frontier - 1 <= selected * previous_depth:
        result.add((previous_depth, selected, frontier - 1))
    for left_selected in range(1, selected):
        right_selected = selected - left_selected
        for left_frontier in range(frontier + 1):
            right_frontier = frontier - left_frontier
            if (
                left_frontier <= left_selected * previous_depth
                and right_frontier <= right_selected * previous_depth
            ):
                result.add((previous_depth, left_selected, left_frontier))
                result.add((previous_depth, right_selected, right_frontier))
    return result


def dependency_closure() -> set[tuple[int, int, int]]:
    needed = {
        (DEPTH, SELECTED, frontier)
        for frontier in range(CAP + 1, LOOSE_MAX + 1)
    }
    pending = list(needed)
    while pending:
        state = pending.pop()
        for dependency in dependencies(*state):
            if dependency not in needed:
                needed.add(dependency)
                pending.append(dependency)
    return needed


def theorem_name(depth: int, selected: int, frontier: int) -> str:
    return f"certificate_{depth}_{selected}_{frontier}"


def depth_name(depth: int) -> str:
    return f"Depth{depth:02d}"


def chunk_name(depth: int, chunk: int) -> str:
    return f"{depth_name(depth)}Chunk{chunk:03d}"


def proof_cost(state: tuple[int, int]) -> int:
    """Deterministic proxy for one unfolded recurrence's simp workload.

    The convolution visits ``(selected - 1) * (frontier + 1)`` products.
    Cell count alone badly underestimates RAM for sparse high-frontier tails,
    so generated chunks are bounded by both declarations and this workload.
    A single cell may exceed the budget and then forms a singleton chunk.
    """
    selected, frontier = state
    return max(1, (selected - 1) * (frontier + 1))


def partition_states(
    states: list[tuple[int, int]],
) -> list[tuple[int, list[tuple[int, int]], int]]:
    chunks: list[tuple[int, list[tuple[int, int]], int]] = []
    current: list[tuple[int, int]] = []
    current_cost = 0
    current_start = 0
    for index, state in enumerate(states):
        state_cost = proof_cost(state)
        if current and (
            len(current) >= CHUNK_SIZE or current_cost + state_cost > CHUNK_COST
        ):
            chunks.append((current_start, current, current_cost))
            current = []
            current_cost = 0
            current_start = index
        current.append(state)
        current_cost += state_cost
    if current:
        chunks.append((current_start, current, current_cost))
    return chunks


def attribute_lines(action: str, names: list[str]) -> list[str]:
    """Keep generated attribute commands readable and parser-friendly."""
    width = 8
    return [
        f"attribute [{action}] " + " ".join(names[start : start + width])
        for start in range(0, len(names), width)
    ]


def lean_prelude(import_name: str) -> list[str]:
    return [
        f"import {import_name}",
        "",
        GENERATED_HEADER,
        "Every declaration uses ordinary kernel-checked arithmetic. -/",
        "",
        "set_option autoImplicit false",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 0",
        "",
        "namespace AspisV6CompactFrontierTailCertificate",
        "",
        "open AspisV6CompactFrontierRecurrence",
        "",
    ]


def depth_states(
    needed: set[tuple[int, int, int]], depth: int
) -> list[tuple[int, int]]:
    return sorted(
        (selected, frontier)
        for state_depth, selected, frontier in needed
        if state_depth == depth
    )


def generate_chunk(
    depth: int,
    chunk: int,
    start_index: int,
    chunk_cost: int,
    states: list[tuple[int, int]],
    tables: list[dict[int, dict[int, int]]],
) -> str:
    import_name = (
        "AspisFormal.V6CompactFrontierRecurrence"
        if depth == 0
        else f"{MODULE_PREFIX}.{depth_name(depth - 1)}"
    )
    lines = lean_prelude(import_name)
    lines.extend(
        [
            f"/-! ## Depth {depth}, chunk {chunk}",
            f"Cells {start_index} through {start_index + len(states) - 1};",
            f"recurrence workload {chunk_cost}. -/",
            "",
        ]
    )
    for selected, frontier in states:
        value = tables[depth].get(selected, {}).get(frontier, 0)
        name = theorem_name(depth, selected, frontier)
        lines.extend(
            [
                f"theorem {name} :",
                f"    frontierCoeff {depth} {selected} {frontier} = {value} := by",
            ]
        )
        if depth == 0:
            lines.append("  norm_num [frontierCoeff]")
        else:
            lines.extend(
                [
                    "  rw [frontierCoeff]",
                    "  norm_num [Finset.sum_range_succ,",
                    "    frontierCoeff_eq_zero_of_frontier_gt_mul]",
                ]
            )
        lines.append("")
    lines.extend(
        [
            "end AspisV6CompactFrontierTailCertificate",
            "",
        ]
    )
    return "\n".join(lines)


def generate_depth_aggregator(
    depth: int,
    chunk_count: int,
    previous_names: list[str],
    current_names: list[str],
) -> str:
    lines = [
        *(
            f"import {MODULE_PREFIX}.{chunk_name(depth, chunk)}"
            for chunk in range(chunk_count)
        ),
        "",
        GENERATED_HEADER,
        "This aggregator keeps only its own depth active in the simp set. -/",
        "",
        "set_option autoImplicit false",
        "",
        "namespace AspisV6CompactFrontierTailCertificate",
        "",
    ]
    if previous_names:
        lines.extend(attribute_lines("-simp", previous_names))
    lines.extend(attribute_lines("simp", current_names))
    lines.extend(
        [
            "",
            "end AspisV6CompactFrontierTailCertificate",
            "",
        ]
    )
    return "\n".join(lines)


def generate_wrapper(tail: int) -> str:
    lines = lean_prelude(f"{MODULE_PREFIX}.{depth_name(DEPTH)}")
    lines.extend(
        [
            "/-- Exact count of schedules rejected solely because their compact",
            "frontier is above the release cap. The range continues to the",
            "proved loose maximum; all coefficients after 224 are checked zero. -/",
            "def compactTail : Nat :=",
            f"  ∑ frontier ∈ Finset.Icc {CAP + 1} {LOOSE_MAX},",
            f"    concreteFrontierCount {DEPTH} {SELECTED} frontier",
            "",
            "def expectedCompactTail : Nat :=",
            f"  {tail}",
            "",
            "theorem compactTail_eq_expected :",
            "    compactTail = expectedCompactTail := by",
            "  norm_num [compactTail, concreteFrontierCount,",
            "    Finset.sum_Icc_succ_top]",
            "",
            "#print axioms compactTail_eq_expected",
            "",
            "end AspisV6CompactFrontierTailCertificate",
            "",
        ]
    )
    return "\n".join(lines)


def generated_files(output: Path) -> dict[Path, str]:
    tables = coefficient_tables()
    needed = dependency_closure()
    assert len(needed) == 4999
    final_row = tables[DEPTH][SELECTED]
    tail = sum(
        final_row.get(frontier, 0) * (1 << frontier)
        for frontier in range(CAP + 1, LOOSE_MAX + 1)
    )
    expected_tail = int(
        "14674433666996641882200248991177161572700984080998586769411569185737146368"
    )
    assert tail == expected_tail

    generated_dir = output.with_suffix("")
    files: dict[Path, str] = {}
    previous_names: list[str] = []
    manifest_depths: list[dict[str, int]] = []
    for depth in range(DEPTH + 1):
        states = depth_states(needed, depth)
        current_names = [theorem_name(depth, *state) for state in states]
        chunks = partition_states(states)
        for chunk, (start_index, chunk_states, chunk_cost) in enumerate(chunks):
            files[generated_dir / f"{chunk_name(depth, chunk)}.lean"] = (
                generate_chunk(
                    depth,
                    chunk,
                    start_index,
                    chunk_cost,
                    chunk_states,
                    tables,
                )
            )
        files[generated_dir / f"{depth_name(depth)}.lean"] = (
            generate_depth_aggregator(
                depth, len(chunks), previous_names, current_names
            )
        )
        manifest_depths.append(
            {
                "depth": depth,
                "cells": len(states),
                "chunks": len(chunks),
                "max_chunk_cells": max(len(chunk_states) for _, chunk_states, _ in chunks),
                "max_chunk_cost": max(chunk_cost for _, _, chunk_cost in chunks),
            }
        )
        previous_names = current_names

    files[output] = generate_wrapper(tail)
    canonical_surface = "".join(
        f"{theorem_name(depth, selected, frontier)}|"
        f"    frontierCoeff {depth} {selected} {frontier} = "
        f"{tables[depth].get(selected, {}).get(frontier, 0)} := by\n"
        for depth in range(DEPTH + 1)
        for selected, frontier in depth_states(needed, depth)
    )
    lean_hashes = {
        str(path.relative_to(output.parent)): hashlib.sha256(
            content.encode("utf-8")
        ).hexdigest()
        for path, content in sorted(files.items(), key=lambda item: str(item[0]))
    }
    manifest = {
        "schema": "aspis-v6-compact-frontier-tail-split-v1",
        "generator": "tools/generate_v6_compact_frontier_tail.py",
        "chunk_size": CHUNK_SIZE,
        "chunk_cost_budget": CHUNK_COST,
        "ordinary_recurrence_cells": len(needed),
        "canonical_theorem_surface_sha256": hashlib.sha256(
            canonical_surface.encode("utf-8")
        ).hexdigest(),
        "non_base_rw_norm_num_cells": len(needed) - len(depth_states(needed, 0)),
        "public_namespace": "AspisV6CompactFrontierTailCertificate",
        "expected_compact_tail": tail,
        "depths": manifest_depths,
        "lean_sha256": lean_hashes,
    }
    files[generated_dir / "manifest.json"] = (
        json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    )
    return files


def existing_generated_files(output: Path) -> set[Path]:
    generated_dir = output.with_suffix("")
    if not generated_dir.exists():
        return set()
    return {
        path
        for path in generated_dir.iterdir()
        if path.is_file() and (path.suffix == ".lean" or path.name == "manifest.json")
    }


def check(output: Path) -> None:
    expected = generated_files(output)
    expected_paths = set(expected)
    actual_paths = existing_generated_files(output)
    if output.exists():
        actual_paths.add(output)
    problems: list[str] = []
    for path in sorted(expected_paths - actual_paths):
        problems.append(f"missing: {path}")
    for path in sorted(actual_paths - expected_paths):
        problems.append(f"unexpected stale generated file: {path}")
    for path in sorted(expected_paths & actual_paths):
        if path.read_text(encoding="utf-8") != expected[path]:
            problems.append(f"changed or stale: {path}")
    if problems:
        raise SystemExit("generated certificate check failed:\n" + "\n".join(problems))
    print(
        f"V6 split certificate: PASS ({len(expected) - 1} generated parts, "
        "4,999 recurrence cells)"
    )


def generate(output: Path) -> None:
    expected = generated_files(output)
    generated_dir = output.with_suffix("")
    generated_dir.mkdir(parents=True, exist_ok=True)
    obsolete = existing_generated_files(output) - set(expected)
    for path in sorted(obsolete):
        path.unlink()
    for path, content in sorted(expected.items(), key=lambda item: str(item[0])):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    parser.add_argument(
        "--check",
        action="store_true",
        help="reject missing, changed, or unexpected generated files",
    )
    args = parser.parse_args()
    if args.check:
        check(args.output)
    else:
        generate(args.output)
        check(args.output)


if __name__ == "__main__":
    main()
