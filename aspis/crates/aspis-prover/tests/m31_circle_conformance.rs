// Candidate-only wire KAT. It binds the distinct discriminator, pinned Stwo
// commit, domain/fiber, all 49x4 M31 symbols, late gamma outputs, normalized
// fold, and secure-circle OOD value. It does not assign a production version.
const CANDIDATE_WIRE_KAT_EXPECTED: [u8; 32] = [
    149, 202, 11, 196, 64, 209, 117, 77, 0, 190, 105, 222, 115, 129, 34, 52, 19, 129, 197, 12, 57,
    92, 42, 233, 4, 248, 173, 132, 85, 21, 213, 136,
];

fn q(values: [u32; 4]) -> QM31 {
    QM31 {
        c0: CM31::new(M31(values[0]), M31(values[1])),
        c1: CM31::new(M31(values[2]), M31(values[3])),
    }
}

fn digest(seed: u32) -> Digest {
    core::array::from_fn(|index| M31(seed + index as u32 * 17))
}

fn spend_trace() -> SpendTraceV4 {
    let nullifier_key = digest(101);
    let input_salt = digest(301);
    let output_salt = digest(501);
    let output_owner_key = digest(701);
    let asset_id = M31(17);
    let value = 1_000_000;
    let value_out = 999_999;
    let fee = 1;
    let owner_key = derive_owner_key(&nullifier_key);
    let note = note_commitment(&owner_key, value, asset_id, &input_salt);
    let path = MerklePath {
        siblings: (0..20)
            .map(|level| digest(1_000 + level as u32 * 31))
            .collect(),
        index: 0x5a5a5,
    };
    let public = SpendPublic {
        anchor: merkle_root(note, &path).unwrap(),
        nullifier: derive_nullifier(&nullifier_key, &input_salt),
        output_commitment: output_commitment(&output_owner_key, value_out, asset_id, &output_salt),
        asset_id,
        fee,
    };
    let witness = SpendWitness {
        nullifier_key,
        input_salt,
        output_salt,
        output_owner_key,
        input_asset_id: asset_id,
        value,
        value_out,
        merkle_path: path,
    };
    build_spend_trace_v4(&public, &witness).unwrap()
}

fn append_qm31(bytes: &mut Vec<u8>, value: QM31) {
    let start = bytes.len();
    bytes.resize(start + 16, 0);
    value.write_le_bytes(&mut bytes[start..]);
}

fn evaluate_current_univariate(coefficients: &[M31], point: CM31) -> CM31 {
    coefficients.iter().rev().fold(CM31::ZERO, |sum, value| {
        sum.mul(point).add(CM31::from_m31(*value))
    })
}

#[test]
fn reference_encoder_matches_pinned_stwo_vectors() {
    assert_eq!(STWO_REFERENCE_COMMIT.len(), 40);

    let short = encode_circle(&[M31(1), M31(3), M31(2), M31(4)], 2);
    assert_eq!(
        short.iter().map(|value| value.0).collect::<Vec<_>>(),
        STWO_LOG2_EVALUATION
    );

    let coefficients = (0..1usize << TRACE_LOG_SIZE)
        .map(|index| M31(((index as u64 * 1_000_003 + 97) % u64::from(P)) as u32))
        .collect::<Vec<_>>();
    let encoded = encode_circle(&coefficients, DOMAIN_LOG_SIZE);
    let selected = STWO_LR10_SELECTED_INDICES.map(|index| encoded[index].0);
    assert_eq!(selected, STWO_LR10_SELECTED_EVALUATIONS);

    for &index in &STWO_LR10_SELECTED_INDICES {
        let point = bit_reversed_domain_point(index, DOMAIN_LOG_SIZE);
        assert_eq!(encoded[index], evaluate_circle_base(&coefficients, point));
    }
}

#[test]
fn spend_trace_circle_encoding_fold_ood_and_late_gamma_conform() {
    let trace = spend_trace();
    assert_eq!(trace.c1.len(), WIDE_V4_C1_COLUMNS);
    assert!(trace
        .c1
        .iter()
        .all(|column| column.len() == 1usize << TRACE_LOG_SIZE));

    // Normative Aspis contract (`aspis-staged-design.md`, Statement
    // Proof-System Shape): these are multilinear message coordinates, not
    // AIR-domain evaluations. The current substrate feeds the same vector
    // directly to `coset_evaluate`, while `WeightAccumulator::from_claim`
    // applies the big-endian eq(z,x) linear form. The circle candidate must
    // preserve that direct message vector and coordinate order; inserting an
    // IFFT here would silently change the MLE claim.
    let mle_point = (0..TRACE_LOG_SIZE)
        .map(|coordinate| {
            q([
                coordinate + 3,
                coordinate + 17,
                coordinate + 31,
                coordinate + 47,
            ])
        })
        .collect::<Vec<_>>();
    let mle_value = multilinear_eval(&trace.c1[0], &mle_point);
    let claim = EvaluationClaim {
        z: mle_point,
        v: mle_value,
    };
    let weights = WeightAccumulator::from_claim(TRACE_LOG_SIZE, Some(&claim));
    let lifted_message = trace.c1[0].iter().copied().map(lift).collect::<Vec<_>>();
    assert_eq!(weights.dot(&lifted_message), mle_value);

    let encoded = trace
        .c1
        .iter()
        .map(|column| encode_circle(column, DOMAIN_LOG_SIZE))
        .collect::<Vec<_>>();

    let slot_start = REFERENCE_FIBER * 4;
    let points = core::array::from_fn::<_, 4, _>(|slot| {
        bit_reversed_domain_point(slot_start + slot, DOMAIN_LOG_SIZE)
    });
    let x = points[0].x;
    let y = points[0].y;
    assert_eq!(points[1], circle::CirclePoint { x, y: y.neg() });
    assert_eq!(
        points[2],
        circle::CirclePoint {
            x: x.neg(),
            y: y.neg()
        }
    );
    assert_eq!(points[3], circle::CirclePoint { x: x.neg(), y });

    let gamma = q([17, 29, 43, 71]);
    let alpha = q([101, 307, 401, 809]);
    let gamma_powers = qm31_power_table::<WIDE_V4_C1_COLUMNS>(gamma);

    let combined_coefficients = (0..1usize << TRACE_LOG_SIZE)
        .map(|row| {
            (0..WIDE_V4_C1_COLUMNS).fold(QM31::ZERO, |sum, column| {
                sum.add(gamma_powers[column].mul_m31(trace.c1[column][row]))
            })
        })
        .collect::<Vec<_>>();

    // Late lift: encode 49 base-field columns first, then gamma-combine their
    // authenticated symbols. This must equal evaluating the gamma-combined
    // secure coefficients at each of the same four circle points.
    let combined_slots = core::array::from_fn::<_, 4, _>(|slot| {
        (0..WIDE_V4_C1_COLUMNS).fold(QM31::ZERO, |sum, column| {
            sum.add(gamma_powers[column].mul_m31(encoded[column][slot_start + slot]))
        })
    });
    for slot in 0..4 {
        let point = circle::SecureCirclePoint {
            x: lift(points[slot].x),
            y: lift(points[slot].y),
        };
        assert_eq!(
            combined_slots[slot],
            evaluate_circle_secure(&combined_coefficients, point)
        );
    }

    // The normalized circle-to-line plus line fold is exactly coefficient
    // folding by (alpha, alpha^2), and the remaining basis begins at pi(x).
    let folded = normalized_fold4(combined_slots, alpha, x, y);
    let folded_coefficients =
        fold_first_two_coefficients(&combined_coefficients, alpha, alpha.square());
    assert_eq!(
        folded,
        evaluate_line_secure(&folded_coefficients, lift(x.mul(x).double().sub(M31::ONE)))
    );

    let folded_late = (0..WIDE_V4_C1_COLUMNS).fold(QM31::ZERO, |sum, column| {
        let slots = core::array::from_fn(|slot| lift(encoded[column][slot_start + slot]));
        sum.add(gamma_powers[column].mul(normalized_fold4(slots, alpha, x, y)))
    });
    assert_eq!(folded, folded_late);

    // Secure-circle OOD relation: evaluate columns then batch, batch
    // coefficients then evaluate, and decompose the first y/x basis factors.
    let ood_point = secure_circle_point(q([911, 1_013, 1_237, 1_423]));
    assert_eq!(ood_point.x.square().add(ood_point.y.square()), QM31::ONE);
    let ood_from_columns = (0..WIDE_V4_C1_COLUMNS).fold(QM31::ZERO, |sum, column| {
        let lifted = trace.c1[column]
            .iter()
            .copied()
            .map(lift)
            .collect::<Vec<_>>();
        sum.add(gamma_powers[column].mul(evaluate_circle_secure(&lifted, ood_point)))
    });
    let ood_combined = evaluate_circle_secure(&combined_coefficients, ood_point);
    let ood_decomposed = evaluate_line_secure(
        &fold_first_two_coefficients(&combined_coefficients, ood_point.y, ood_point.x),
        double_x_secure(ood_point.x),
    );
    assert_eq!(ood_from_columns, ood_combined);
    assert_eq!(ood_combined, ood_decomposed);

    // Candidate wire/KAT requirement only: 4 slots x 49 M31 values are a
    // distinct 784-byte leaf. This does not alter v3/v4 production parsing.
    let mut leaf = Vec::with_capacity(CANDIDATE_C1_LEAF_BYTES);
    for slot in 0..4 {
        for column in &encoded {
            leaf.extend_from_slice(&column[slot_start + slot].to_le_bytes());
        }
    }
    assert_eq!(leaf.len(), CANDIDATE_C1_LEAF_BYTES);

    let mut kat = Vec::new();
    kat.extend_from_slice(CANDIDATE_WIRE_DISCRIMINATOR);
    kat.extend_from_slice(STWO_REFERENCE_COMMIT.as_bytes());
    kat.extend_from_slice(MESSAGE_COORDINATE_ORDER);
    kat.extend_from_slice(REQUIRED_OOD_WEIGHT_ACCUMULATOR);
    kat.extend_from_slice(REQUIRED_TRANSCRIPT_KAT);
    kat.extend_from_slice(&TRACE_LOG_SIZE.to_le_bytes());
    kat.extend_from_slice(&DOMAIN_LOG_SIZE.to_le_bytes());
    kat.extend_from_slice(&(REFERENCE_FIBER as u32).to_le_bytes());
    kat.extend_from_slice(&leaf);
    for value in combined_slots {
        append_qm31(&mut kat, value);
    }
    append_qm31(&mut kat, folded);
    append_qm31(&mut kat, ood_combined);
    assert_eq!(
        <[u8; 32]>::from(Sha256::digest(&kat)),
        CANDIDATE_WIRE_KAT_EXPECTED
    );
}

#[test]
fn current_univariate_conjugation_pairs_reverse_partner_fibers() {
    let trace = spend_trace();
    let geometry = layer_geometry(&PROFILE_CAPACITY_LR10_Q36_G32, 0);
    let fiber_count = geometry.fiber_count as usize;
    let domain_size = geometry.domain_size as usize;
    assert_eq!(domain_size, 4 * fiber_count);

    for fiber in [0usize, 1, 137, 511, 512, 1_023] {
        let partner = fiber_count - 1 - fiber;
        assert_ne!(partner, fiber);
        for column in &trace.c1 {
            let leaf = core::array::from_fn::<_, 4, _>(|slot| {
                let index = fiber + slot * fiber_count;
                evaluate_current_univariate(column, domain_point(&geometry, index as u32))
            });
            let partner_leaf = core::array::from_fn::<_, 4, _>(|slot| {
                let index = partner + slot * fiber_count;
                evaluate_current_univariate(column, domain_point(&geometry, index as u32))
            });
            assert_eq!(
                partner_leaf,
                [
                    leaf[3].conjugate(),
                    leaf[2].conjugate(),
                    leaf[1].conjugate(),
                    leaf[0].conjugate(),
                ]
            );
        }
    }

    // Pairing halves the number of layer-zero leaves, but not one queried
    // fiber's payload: its four points belong to four distinct conjugacy
    // pairs whose partners live in the reversed partner fiber. Moreover 512
    // leaves do not fit the current pure-radix-4 tree shape.
    assert_eq!(fiber_count, 1_024);
    assert_eq!(fiber_count / 2, 512);
    assert_eq!(4 * 8, 32);
    assert_eq!(4 * WIDE_V4_C1_COLUMNS * 8, 1_568);
    assert_ne!((fiber_count / 2).ilog2() % 2, 0);
}
