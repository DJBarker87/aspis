//! Regenerate the allocation-bounded Pool V1 payment terminal constants from
//! the independent host semantic registry.

use std::collections::BTreeSet;

use aspis_statement::pool_v1::{
    payment_hiding::pool_v1_payment_relation_free_mask_fingerprint_v1,
    payment_semantic_registry::{
        build_pool_v1_payment_semantic_registry_v1, pool_v1_payment_aux_cell_is_used_v1,
        pool_v1_payment_semantic_registry_fingerprint_v1, PoolV1PaymentCopyTupleV1,
        PoolV1PaymentTupleLimbV1,
    },
    PoolV1PaymentTraceVariantV1,
};

#[derive(Clone, PartialEq, Eq)]
struct Pattern {
    kinds: [u8; 16],
    columns: [u8; 16],
    scales: [u32; 16],
    offsets: [u32; 16],
}

fn pattern(tuple: PoolV1PaymentCopyTupleV1) -> Pattern {
    let mut output = Pattern {
        kinds: [0; 16],
        columns: [0; 16],
        scales: [0; 16],
        offsets: [0; 16],
    };
    for (index, limb) in tuple.limbs.into_iter().enumerate() {
        match limb {
            PoolV1PaymentTupleLimbV1::Zero => {}
            PoolV1PaymentTupleLimbV1::Constant(value) => {
                output.kinds[index] = 1;
                output.offsets[index] = value.0;
            }
            PoolV1PaymentTupleLimbV1::AffineCell {
                cell,
                scale,
                offset,
            } => {
                assert_eq!(cell.row, tuple.row);
                output.kinds[index] = 2;
                output.columns[index] = cell.column;
                output.scales[index] = scale.0;
                output.offsets[index] = offset.0;
            }
        }
    }
    output
}

fn fnv_rows(rows: &BTreeSet<u16>) -> u64 {
    let mut hash = 0xcbf2_9ce4_8422_2325u64;
    for row in rows {
        for byte in row.to_le_bytes() {
            hash ^= u64::from(byte);
            hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    hash
}

fn emit_variant(name: &str, variant: PoolV1PaymentTraceVariantV1) {
    let registry = build_pool_v1_payment_semantic_registry_v1(variant).unwrap();
    let fingerprint = pool_v1_payment_semantic_registry_fingerprint_v1(&registry).unwrap();
    let mut patterns = Vec::<Pattern>::new();
    for link in &registry.links {
        for tuple in [link.producer, link.consumer] {
            let candidate = pattern(tuple);
            if !patterns.contains(&candidate) {
                patterns.push(candidate);
            }
        }
    }

    let active_rows = registry
        .links
        .iter()
        .flat_map(|link| [link.producer.row, link.consumer.row])
        .collect::<BTreeSet<_>>();
    let mut active_masks = [0u16; 64];
    for &row in &active_rows {
        active_masks[usize::from(row) >> 4] |= 1 << (usize::from(row) & 15);
    }
    let active_fingerprint = fnv_rows(&active_rows);

    println!("pub(crate) const {name}_REGISTRY_FINGERPRINT: u64 = {fingerprint:#018x};");
    println!("pub(crate) const {name}_ACTIVE_ROWS_FINGERPRINT: u64 = {active_fingerprint:#018x};");
    println!("pub(crate) const {name}_ACTIVE_ROW_MASKS: [u16; 64] = {active_masks:?};");
    println!(
        "pub(crate) const {name}_COPY_PATTERNS: [CompiledPoolV1PaymentPattern; {}] = [",
        patterns.len()
    );
    for item in &patterns {
        println!(
            "    CompiledPoolV1PaymentPattern {{ kinds: {:?}, columns: {:?}, scales: {:?}, offsets: {:?} }},",
            item.kinds, item.columns, item.scales, item.offsets
        );
    }
    println!("];");

    let mut producer_arity = [0u8; 1024];
    let mut consumer_arity = [0u8; 1024];
    println!(
        "pub(crate) const {name}_COPY_LINKS: [CompiledPoolV1PaymentLink; {}] = [",
        registry.links.len()
    );
    for link in &registry.links {
        let mut endpoints = [(0u16, 0u8, 0u8); 2];
        for (index, (tuple, arity)) in [
            (link.producer, &mut producer_arity),
            (link.consumer, &mut consumer_arity),
        ]
        .into_iter()
        .enumerate()
        {
            let row = usize::from(tuple.row);
            let slot = arity[row];
            assert!(slot < 2);
            arity[row] += 1;
            let key = pattern(tuple);
            let pattern = patterns
                .iter()
                .position(|candidate| *candidate == key)
                .unwrap();
            endpoints[index] = (tuple.row, slot, pattern as u8);
        }
        println!(
            "    CompiledPoolV1PaymentLink {{ tag: {}, producer: CompiledPoolV1PaymentEndpoint {{ row: {}, slot: {}, pattern: {} }}, consumer: CompiledPoolV1PaymentEndpoint {{ row: {}, slot: {}, pattern: {} }} }},",
            link.tag.0,
            endpoints[0].0,
            endpoints[0].1,
            endpoints[0].2,
            endpoints[1].0,
            endpoints[1].1,
            endpoints[1].2,
        );
    }
    println!("];");
}

fn main() {
    println!("// @generated by examples/generate_pool_v1_payment_terminal_constants.rs.");
    println!("// Do not hand-edit. Host identity and off-domain tests bind these constants.");
    println!();

    let relation_free_mask_fingerprint =
        pool_v1_payment_relation_free_mask_fingerprint_v1().unwrap();
    println!(
        "pub(crate) const RELATION_FREE_MASK_FINGERPRINT: u64 = {relation_free_mask_fingerprint:#018x};"
    );
    println!();

    let auxiliary_used_masks: [u16; 96] = core::array::from_fn(|offset| {
        let row = 784 + offset;
        (0..16).fold(0u16, |mask, column| {
            if pool_v1_payment_aux_cell_is_used_v1(row, column) {
                mask | (1 << column)
            } else {
                mask
            }
        })
    });
    let mut auxiliary_fingerprint = 0xcbf2_9ce4_8422_2325u64;
    for mask in auxiliary_used_masks {
        for byte in mask.to_le_bytes() {
            auxiliary_fingerprint ^= u64::from(byte);
            auxiliary_fingerprint = auxiliary_fingerprint.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    println!(
        "pub(crate) const AUXILIARY_USED_COLUMN_MASKS_FINGERPRINT: u64 = {auxiliary_fingerprint:#018x};"
    );
    println!("pub(crate) const AUXILIARY_USED_COLUMN_MASKS: [u16; 96] = {auxiliary_used_masks:?};");
    println!();

    emit_variant(
        "PRIVATE_TRANSFER",
        PoolV1PaymentTraceVariantV1::PrivateTransfer,
    );
    println!();
    emit_variant("WITHDRAWAL", PoolV1PaymentTraceVariantV1::Withdrawal);
}
