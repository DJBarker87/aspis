use aspis_core::field::M31;
use aspis_statement::{
    pool_v1::{pool_v1_tree_parent, POOL_V1_PAIR_TREE_DEPTH},
    poseidon2::DIGEST_ELEMS,
};

fn main() {
    let zero = [M31::ZERO; DIGEST_ELEMS];
    let mut roots = [zero; POOL_V1_PAIR_TREE_DEPTH + 1];
    roots[0] = pool_v1_tree_parent(&zero, &zero);
    for level in 0..POOL_V1_PAIR_TREE_DEPTH {
        roots[level + 1] = pool_v1_tree_parent(&roots[level], &roots[level]);
    }
    println!("// @generated by `generate_pool_v1_pair_empty_roots`; do not edit by hand.");
    println!("pub const POOL_V1_PAIR_EMPTY_ROOTS_V1: [[u32; 8]; 21] = [");
    for root in roots {
        println!("    {:?},", root.map(|limb| limb.0));
    }
    println!("];");
}
