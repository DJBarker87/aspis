//! Regenerate the allocation-bounded Pool V1 pair-forest Copy-lane constants
//! from the independent host registry.

use std::collections::BTreeSet;

use aspis_statement::pool_v1::{
    pair_forest_trace::build_pool_v1_pair_forest_copy_registry_v1,
    pair_trace::{PoolV1PairCopyWeightV1, PoolV1PairTupleLimbV1},
};

#[derive(Clone, PartialEq, Eq)]
struct Pattern {
    kinds: [u8; 16],
    columns: [u8; 16],
    offsets: [u32; 16],
}

fn pattern(tuple: aspis_statement::pool_v1::pair_trace::PoolV1PairCopyTupleV1) -> Pattern {
    let mut output = Pattern {
        kinds: [0; 16],
        columns: [0; 16],
        offsets: [0; 16],
    };
    for (index, limb) in tuple.limbs.into_iter().enumerate() {
        match limb {
            PoolV1PairTupleLimbV1::Zero => {}
            PoolV1PairTupleLimbV1::Cell { source, offset } => {
                assert_eq!(source.cell.row, tuple.row);
                output.kinds[index] = 1;
                output.columns[index] = source.cell.column;
                output.offsets[index] = offset.0;
            }
        }
    }
    output
}

fn fnv_bytes(bytes: impl IntoIterator<Item = u8>) -> u64 {
    let mut hash = 0xcbf2_9ce4_8422_2325u64;
    for byte in bytes {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    hash
}

fn main() {
    let registry = build_pool_v1_pair_forest_copy_registry_v1().unwrap();
    let mut patterns = Vec::<Pattern>::new();
    for link in &registry {
        for tuple in [link.producer, link.consumer] {
            let candidate = pattern(tuple);
            if !patterns.contains(&candidate) {
                patterns.push(candidate);
            }
        }
    }

    let active_rows = registry
        .iter()
        .flat_map(|link| [link.producer.row, link.consumer.row])
        .collect::<BTreeSet<_>>();
    let mut active_masks = [0u16; 64];
    for &row in &active_rows {
        active_masks[usize::from(row) >> 4] |= 1 << (usize::from(row) & 15);
    }
    let active_fingerprint = fnv_bytes(active_rows.iter().flat_map(|row: &u16| row.to_le_bytes()));

    println!("// @generated by examples/generate_pool_v1_pair_forest_copy_terminal_constants.rs.");
    println!("// Do not hand-edit. Host identity and off-domain tests bind these constants.");
    println!();
    println!("pub(crate) const ACTIVE_ROWS_FINGERPRINT: u64 = {active_fingerprint:#018x};");
    println!("pub(crate) const ACTIVE_ROW_MASKS: [u16; 64] = {active_masks:?};");
    println!();
    println!(
        "pub(crate) const COPY_PATTERNS: [CompiledPoolV1PairForestPattern; {}] = [",
        patterns.len()
    );
    for item in &patterns {
        println!(
            "    CompiledPoolV1PairForestPattern {{ kinds: {:?}, columns: {:?}, offsets: {:?} }},",
            item.kinds, item.columns, item.offsets
        );
    }
    println!("];");
    println!();

    let mut producer_arity = [0u8; 1024];
    let mut consumer_arity = [0u8; 1024];
    println!(
        "pub(crate) const COPY_LINKS: [CompiledPoolV1PairForestLink; {}] = [",
        registry.len()
    );
    for link in &registry {
        let mut endpoints = [(0u16, 0u8, 0u8); 2];
        for (index, (tuple, arity)) in [
            (link.producer, &mut producer_arity),
            (link.consumer, &mut consumer_arity),
        ]
        .into_iter()
        .enumerate()
        {
            let row = usize::from(tuple.row);
            let slot = arity[row];
            assert!(slot < 2);
            arity[row] += 1;
            let key = pattern(tuple);
            let pattern = patterns
                .iter()
                .position(|candidate| *candidate == key)
                .unwrap();
            endpoints[index] = (tuple.row, slot, pattern as u8);
        }
        let (weight_kind, weight_level) = match link.weight {
            PoolV1PairCopyWeightV1::One => (0, 0),
            PoolV1PairCopyWeightV1::PrivateTransferOnly => (1, 0),
            PoolV1PairCopyWeightV1::WithdrawalOnly => (2, 0),
            PoolV1PairCopyWeightV1::AppendCurrentLeft { level } => (3, level),
            PoolV1PairCopyWeightV1::AppendCurrentRight { level } => (4, level),
        };
        println!(
            "    CompiledPoolV1PairForestLink {{ tag: {}, weight_kind: {weight_kind}, weight_level: {weight_level}, producer: CompiledPoolV1PairForestEndpoint {{ row: {}, slot: {}, pattern: {} }}, consumer: CompiledPoolV1PairForestEndpoint {{ row: {}, slot: {}, pattern: {} }} }},",
            link.tag.0,
            endpoints[0].0,
            endpoints[0].1,
            endpoints[0].2,
            endpoints[1].0,
            endpoints[1].1,
            endpoints[1].2,
        );
    }
    println!("];");
}
