//! Regenerate the SBF-safe state-only terminal constants from the independent
//! host layout builders. The checked-in constants are deliberately consumed
//! without these builders on Solana.

use std::collections::BTreeSet;

use aspis_core::field::M31;
use aspis_statement::{
    build_state_only_cell_map_v4, permutation_block_schedule, state_only_copy_layout_v4,
    witness_aux_layout, HashInvocationKind, TraceCell, TupleLimb,
    AUX_ABSORPTION_PRODUCER_ROW_START, BLOCK_ROWS, PERMUTATION_COUNT,
};

fn endpoint_key(tuple: &aspis_statement::CopyTuple) -> (u16, u64) {
    let mut present = 0u16;
    let mut columns = 0u64;
    for (limb, value) in tuple.limbs.iter().enumerate() {
        if let TupleLimb::Cell(cell) = value {
            present |= 1 << limb;
            columns |= u64::from(cell.column) << (4 * limb);
        }
    }
    (present, columns)
}

fn endpoint(tuple: &aspis_statement::CopyTuple, row: u16, slot: u8) -> String {
    let (present, columns) = endpoint_key(tuple);
    format!(
        "CompiledCopyEndpoint {{ row: {row}, slot: {slot}, present: 0x{present:04x}, columns: 0x{columns:016x} }}"
    )
}

fn vector_rank(vectors: &[Vec<M31>]) -> usize {
    if vectors.is_empty() {
        return 0;
    }
    let columns = vectors[0].len();
    let mut matrix = vectors.to_vec();
    let mut rank = 0usize;
    for column in 0..columns {
        let Some(pivot) = (rank..matrix.len()).find(|&row| matrix[row][column] != M31::ZERO) else {
            continue;
        };
        matrix.swap(rank, pivot);
        let inverse = matrix[rank][column].inv();
        for entry in column..columns {
            matrix[rank][entry] = matrix[rank][entry].mul(inverse);
        }
        for row in rank + 1..matrix.len() {
            let scale = matrix[row][column];
            if scale == M31::ZERO {
                continue;
            }
            for entry in column..columns {
                matrix[row][entry] = matrix[row][entry].sub(scale.mul(matrix[rank][entry]));
            }
        }
        rank += 1;
        if rank == matrix.len() {
            break;
        }
    }
    rank
}

fn basis_coordinates(basis: &[Vec<M31>], target: &[M31]) -> Vec<M31> {
    let variables = basis.len();
    let mut equations = (0..target.len())
        .map(|coordinate| {
            let mut row = basis
                .iter()
                .map(|factor| factor[coordinate])
                .collect::<Vec<_>>();
            row.push(target[coordinate]);
            row
        })
        .collect::<Vec<_>>();
    let mut pivot_rows = vec![0usize; variables];
    let mut next_row = 0usize;
    for variable in 0..variables {
        let pivot = (next_row..equations.len())
            .find(|&row| equations[row][variable] != M31::ZERO)
            .expect("selected copy-routing basis is singular");
        equations.swap(next_row, pivot);
        let inverse = equations[next_row][variable].inv();
        for entry in variable..=variables {
            equations[next_row][entry] = equations[next_row][entry].mul(inverse);
        }
        for row in 0..equations.len() {
            if row == next_row {
                continue;
            }
            let scale = equations[row][variable];
            if scale == M31::ZERO {
                continue;
            }
            for entry in variable..=variables {
                equations[row][entry] =
                    equations[row][entry].sub(scale.mul(equations[next_row][entry]));
            }
        }
        pivot_rows[variable] = next_row;
        next_row += 1;
    }
    let coordinates = pivot_rows
        .into_iter()
        .map(|row| equations[row][variables])
        .collect::<Vec<_>>();
    for coordinate in 0..target.len() {
        let reconstructed = basis
            .iter()
            .zip(&coordinates)
            .fold(M31::ZERO, |sum, (factor, coefficient)| {
                sum.add(factor[coordinate].mul(*coefficient))
            });
        assert_eq!(reconstructed, target[coordinate]);
    }
    coordinates
}

fn main() {
    println!("// @generated by examples/generate_state_only_terminal_constants.rs.");
    println!("// Do not hand-edit. The host identity tests bind this file to the frozen layout.");
    println!();
    let layout = state_only_copy_layout_v4().unwrap();
    let active_rows = layout
        .links
        .iter()
        .flat_map(|link| [link.producer_row, link.consumer_row])
        .collect::<BTreeSet<_>>();
    let mut active_fingerprint = 0xcbf2_9ce4_8422_2325u64;
    for row in &active_rows {
        for byte in row.to_le_bytes() {
            active_fingerprint ^= u64::from(byte);
            active_fingerprint = active_fingerprint.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    println!(
        "pub(crate) const COMPILED_COPY_ACTIVE_ROWS: [u16; {}] = {:?};",
        active_rows.len(),
        active_rows.iter().copied().collect::<Vec<_>>()
    );
    println!(
        "pub(crate) const COMPILED_COPY_ACTIVE_ROWS_FINGERPRINT: u64 = {active_fingerprint:#018x};"
    );
    let mut active_low_masks = [0u16; 64];
    for &row in &active_rows {
        active_low_masks[usize::from(row) >> 4] |= 1 << (usize::from(row) & 15);
    }
    let distinct_low_masks = active_low_masks
        .iter()
        .copied()
        .filter(|&mask| mask != 0)
        .collect::<BTreeSet<_>>();
    println!(
        "pub(crate) const COMPILED_COPY_ACTIVE_FACTORS: [(u64, u16); {}] = [",
        distinct_low_masks.len()
    );
    for low_mask in distinct_low_masks {
        let high_mask = active_low_masks
            .iter()
            .enumerate()
            .filter(|(_, mask)| **mask == low_mask)
            .fold(0u64, |mask, (high, _)| mask | (1u64 << high));
        println!("    (0x{high_mask:016x}, 0x{low_mask:04x}),");
    }
    println!("];");
    let mut producer_arity = [0u8; 1024];
    let mut consumer_arity = [0u8; 1024];
    let mut patterns = BTreeSet::new();
    for link in &layout.links {
        patterns.insert(endpoint_key(&link.producer));
        patterns.insert(endpoint_key(&link.consumer));
    }
    let patterns = patterns.into_iter().collect::<Vec<_>>();
    println!(
        "pub(crate) const COPY_PATTERNS: [(u16, u64); {}] = [",
        patterns.len()
    );
    for &(present, columns) in &patterns {
        println!("    (0x{present:04x}, 0x{columns:016x}),");
    }
    println!("];");

    let matrix_count = 4 * (2 + patterns.len());
    let mut matrices = vec![vec![vec![M31::ZERO; 16]; 64]; matrix_count];
    let mut pattern_masks = [0u16; 4];
    let mut matrix_producer_arity = [0u8; 1024];
    let mut matrix_consumer_arity = [0u8; 1024];
    for link in &layout.links {
        let producer_row = usize::from(link.producer_row);
        let consumer_row = usize::from(link.consumer_row);
        let producer_slot = usize::from(matrix_producer_arity[producer_row]);
        let consumer_slot = 2 + usize::from(matrix_consumer_arity[consumer_row]);
        matrix_producer_arity[producer_row] += 1;
        matrix_consumer_arity[consumer_row] += 1;
        for (slot, row, key) in [
            (producer_slot, producer_row, endpoint_key(&link.producer)),
            (consumer_slot, consumer_row, endpoint_key(&link.consumer)),
        ] {
            assert!(slot < 4, "copy endpoint arity exceeds two at row {row}");
            let pattern = patterns
                .iter()
                .position(|candidate| *candidate == key)
                .unwrap();
            let high = row >> 4;
            let low = row & 15;
            let base = slot * (2 + patterns.len());
            matrices[base][high][low] = matrices[base][high][low].add(M31::ONE);
            matrices[base + 1][high][low] = matrices[base + 1][high][low].add(link.tag);
            matrices[base + 2 + pattern][high][low] =
                matrices[base + 2 + pattern][high][low].add(M31::ONE);
            pattern_masks[slot] |= 1 << pattern;
        }
    }

    let mut raw_terms = Vec::<(u8, u8, u8)>::new();
    let mut unique_left = Vec::<Vec<M31>>::new();
    let mut unique_right = Vec::<Vec<M31>>::new();
    for (matrix_index, matrix) in matrices.iter_mut().enumerate() {
        loop {
            let pivot = (0..64).find_map(|row| {
                (0..16)
                    .find(|&column| matrix[row][column] != M31::ZERO)
                    .map(|column| (row, column))
            });
            let Some((pivot_row, pivot_column)) = pivot else {
                break;
            };
            let inverse = matrix[pivot_row][pivot_column].inv();
            let left = (0..64)
                .map(|row| matrix[row][pivot_column])
                .collect::<Vec<_>>();
            let right = (0..16)
                .map(|column| matrix[pivot_row][column].mul(inverse))
                .collect::<Vec<_>>();
            let left_id = unique_left
                .iter()
                .position(|factor| *factor == left)
                .unwrap_or_else(|| {
                    unique_left.push(left.clone());
                    unique_left.len() - 1
                });
            let right_id = unique_right
                .iter()
                .position(|factor| *factor == right)
                .unwrap_or_else(|| {
                    unique_right.push(right.clone());
                    unique_right.len() - 1
                });
            raw_terms.push((matrix_index as u8, left_id as u8, right_id as u8));
            for row in 0..64 {
                for column in 0..16 {
                    matrix[row][column] = matrix[row][column].sub(left[row].mul(right[column]));
                }
            }
        }
    }

    let mut entries = Vec::<(u8, u32)>::new();
    let mut left_factors = Vec::<(u16, u8)>::new();
    for factor in &unique_left {
        let start = entries.len();
        for (index, coefficient) in factor.iter().enumerate() {
            if *coefficient != M31::ZERO {
                entries.push((index as u8, coefficient.0));
            }
        }
        left_factors.push((start as u16, (entries.len() - start) as u8));
    }
    let mut right_factors = Vec::<(u16, u8)>::new();
    for factor in &unique_right {
        let start = entries.len();
        for (index, coefficient) in factor.iter().enumerate() {
            if *coefficient != M31::ZERO {
                entries.push((index as u8, coefficient.0));
            }
        }
        right_factors.push((start as u16, (entries.len() - start) as u8));
    }

    // The generated left factors have only rank fifteen. Select the
    // minimum-support basis (the independent-set greedy is exact for this
    // weighted linear matroid), then derive every reconstruction coefficient
    // independently from the full 64-coordinate factors.
    let mut left_order = (0..unique_left.len()).collect::<Vec<_>>();
    left_order.sort_by_key(|&index| {
        (
            unique_left[index]
                .iter()
                .filter(|&&value| value != M31::ZERO)
                .count(),
            index,
        )
    });
    let mut left_basis_indices = Vec::new();
    let mut left_basis = Vec::new();
    for index in left_order {
        let mut candidate = left_basis.clone();
        candidate.push(unique_left[index].clone());
        if vector_rank(&candidate) > left_basis.len() {
            left_basis_indices.push(index);
            left_basis.push(unique_left[index].clone());
        }
    }
    left_basis_indices.sort_unstable();
    left_basis = left_basis_indices
        .iter()
        .map(|&index| unique_left[index].clone())
        .collect();
    assert_eq!(left_basis_indices.len(), 15);
    let mut left_reconstruction_entries = Vec::<(u8, u32)>::new();
    let mut left_reconstruction_factors = Vec::<(u8, u8)>::new();
    for (index, factor) in unique_left.iter().enumerate() {
        let start = left_reconstruction_entries.len();
        if !left_basis_indices.contains(&index) {
            for (basis, coefficient) in basis_coordinates(&left_basis, factor)
                .into_iter()
                .enumerate()
            {
                if coefficient != M31::ZERO {
                    left_reconstruction_entries.push((basis as u8, coefficient.0));
                }
            }
        }
        left_reconstruction_factors.push((
            start as u8,
            (left_reconstruction_entries.len() - start) as u8,
        ));
    }

    let mut pair_terms = Vec::<(u8, u8, u8, u8)>::new();
    let mut destinations = Vec::<u8>::new();
    let mut emitted_pairs = BTreeSet::new();
    for &(_, left, right) in &raw_terms {
        if !emitted_pairs.insert((left, right)) {
            continue;
        }
        let start = destinations.len();
        destinations.extend(raw_terms.iter().filter_map(
            |&(matrix, candidate_left, candidate_right)| {
                (candidate_left == left && candidate_right == right).then_some(matrix)
            },
        ));
        pair_terms.push((left, right, start as u8, (destinations.len() - start) as u8));
    }

    println!(
        "pub(crate) const COPY_ROUTING_LEFT_FACTORS: [(u16, u8); {}] = {:?};",
        left_factors.len(),
        left_factors
    );
    println!(
        "pub(crate) const COPY_ROUTING_RIGHT_FACTORS: [(u16, u8); {}] = {:?};",
        right_factors.len(),
        right_factors
    );
    println!(
        "pub(crate) const COPY_ROUTING_ENTRIES: [(u8, u32); {}] = {:?};",
        entries.len(),
        entries
    );
    println!(
        "pub(crate) const COPY_ROUTING_LEFT_BASIS_FACTORS: [u8; {}] = {:?};",
        left_basis_indices.len(),
        left_basis_indices
    );
    println!(
        "pub(crate) const COPY_ROUTING_LEFT_RECONSTRUCTION_FACTORS: [(u8, u8); {}] = {:?};",
        left_reconstruction_factors.len(),
        left_reconstruction_factors
    );
    println!(
        "pub(crate) const COPY_ROUTING_LEFT_RECONSTRUCTION_ENTRIES: [(u8, u32); {}] = {:?};",
        left_reconstruction_entries.len(),
        left_reconstruction_entries
    );
    println!(
        "pub(crate) const COPY_ROUTING_PAIR_TERMS: [(u8, u8, u8, u8); {}] = {:?};",
        pair_terms.len(),
        pair_terms
    );
    println!(
        "pub(crate) const COPY_ROUTING_DESTINATIONS: [u8; {}] = {:?};",
        destinations.len(),
        destinations
    );
    println!(
        "pub(crate) const COPY_ROUTING_PATTERN_MASKS: [u16; 4] = {:?};",
        pattern_masks
    );

    println!(
        "pub(crate) const COMPILED_COPY_LINKS: [CompiledCopyLink; {}] = [",
        layout.links.len()
    );
    for link in layout.links {
        let producer_row = usize::from(link.producer_row);
        let consumer_row = usize::from(link.consumer_row);
        let producer_slot = producer_arity[producer_row];
        let consumer_slot = consumer_arity[consumer_row];
        producer_arity[producer_row] += 1;
        consumer_arity[consumer_row] += 1;
        println!(
            "    CompiledCopyLink {{ tag: {}, producer: {}, consumer: {} }},",
            link.tag.0,
            endpoint(&link.producer, link.producer_row, producer_slot),
            endpoint(&link.consumer, link.consumer_row, consumer_slot),
        );
    }
    println!("];");

    println!("pub(crate) const ABSORPTION_ZERO_MASKS: [u16; {PERMUTATION_COUNT}] = [");
    for block in 0..PERMUTATION_COUNT {
        let schedule = permutation_block_schedule(block).unwrap();
        let mut mask = 0u16;
        for lane in 0..16 {
            let has_carry_payload =
                matches!(block, 0 | 2 | 3 | 47) || ((4..=42).contains(&block) && block & 1 == 0);
            let zero = if lane < 8 {
                lane >= usize::from(schedule.absorbed_len)
            } else {
                !has_carry_payload
            };
            if zero {
                mask |= 1 << lane;
            }
        }
        println!("    0x{mask:04x}, // row {}", block * BLOCK_ROWS + 12);
    }
    println!("];");

    println!("pub(crate) const INITIAL_BLOCKS: [(u16, u32, u32); 24] = [");
    for block in 0..PERMUTATION_COUNT {
        let schedule = permutation_block_schedule(block).unwrap();
        if schedule.chunk_index != 0 {
            continue;
        }
        let (domain, length) = match schedule.invocation {
            HashInvocationKind::OwnerKey => (M31(0x4153_0001), 8),
            HashInvocationKind::Note => (M31(0x4153_0003), 18),
            HashInvocationKind::MerkleLevel(_) => (M31(0x4153_0005), 16),
            HashInvocationKind::Nullifier => (M31(0x4153_0002), 16),
            HashInvocationKind::Output => (M31(0x4153_0003), 18),
        };
        println!("    ({}, {}, {}),", block * BLOCK_ROWS, domain.0, length);
    }
    println!("];");

    let map = build_state_only_cell_map_v4().unwrap();
    let aux = witness_aux_layout();
    let output_old = TraceCell {
        row: (AUX_ABSORPTION_PRODUCER_ROW_START + 47) as u16,
        column: 34,
    };
    println!("pub(crate) const INPUT_ASSET_CELL: (u16, u8) = {:?};", {
        let cell = map.map(aux.input_asset_id).unwrap();
        (cell.row, cell.column)
    });
    println!("pub(crate) const OUTPUT_ASSET_CELL: (u16, u8) = {:?};", {
        let cell = map.map(output_old).unwrap();
        (cell.row, cell.column)
    });
}
